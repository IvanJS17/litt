// LiTT training (docs/training.md, "Authorship of the work"): an ESTIMATE of
// how much of a version's text came from the assistant, computed from what
// LiTT recorded and nothing else. It is not an AI-text detector, it stores
// nothing, and it never guesses: a sentence the records cannot place is
// "undetermined".
//
// The rule, in full (the screen states it too):
//   1. The version's text is split into sentences (lines, and ends of
//      sentence marks followed by a capital, so "Art. 5" stays whole); a sentence is compared after lower-casing and
//      collapsing white space, character for character otherwise.
//   2. AI: the sentence appears literally in the text of an assistant edit a
//      person ACCEPTED, or in the starting text when that was generated by
//      the assistant.
//   3. Undetermined: it appears literally in a pending (undecided) assistant
//      edit; in the starting text when that came in as an uploaded file (LiTT
//      does not know who wrote a file); it is shorter than
//      AUTHORSHIP_MIN_WORDS words yet equal to an assistant sentence (too
//      short to tell chance from copying); or the starting text is unknown.
//   4. Person: everything else, i.e. text that entered through edits made in
//      LiTT and matches nothing the assistant produced. A sentence a person
//      rewrites stops matching, so it is theirs.
// Shares are rounded to multiples of AUTHORSHIP_ROUND_TO percent.

import type {
  DocumentAuthorship,
  DocumentAuthorshipBaseline,
  DocumentAuthorshipWords,
} from "@mike/contracts";

/** Longest text (in characters) the estimate reads; above it the answer is "too large". */
export const AUTHORSHIP_MAX_CHARS = 200_000;
/** Sentences with fewer words than this cannot be told apart from chance. */
export const AUTHORSHIP_MIN_WORDS = 3;
/** Percent step of the reported shares. */
export const AUTHORSHIP_ROUND_TO = 5;

export type AuthorshipEdit = {
  status: "pending" | "accepted" | "rejected";
  inserted_text: string;
};

export type AuthorshipBaselineInput =
  | { kind: "ai" | "file"; text: string }
  | { kind: "unknown" };

export type AuthorshipInput = {
  /** The version's extracted text. */
  text: string;
  /** Assistant edits recorded for the version and the versions it came from. */
  edits: readonly AuthorshipEdit[];
  baseline: AuthorshipBaselineInput;
  textlessPages?: number;
};

export type AuthorshipEstimate = Pick<
  DocumentAuthorship,
  "baseline" | "words" | "shares" | "edits" | "textless_pages"
>;

// Extraction markers ("[Page 2]", "## Slide 3", "[Page 2 form fields]", the
// notice about scanned pages) are structure, not writing.
const MARKER_LINE =
  /^\s*(?:\[(?:pages?|slide|sheet)\b[^\]]*\]|#{1,6}\s*(?:page|slide|sheet)\b.*)\s*$/i;

/** Sentences of `text`, without extraction markers. */
export function splitSentences(text: string): string[] {
  const out: string[] = [];
  for (const line of text.normalize("NFC").split(/\r?\n/)) {
    if (!line.trim() || MARKER_LINE.test(line)) continue;
    for (const part of line.split(/(?<=[.!?…;])\s+(?=[\p{Lu}¿¡"“«(\[])/u)) {
      const trimmed = part.trim();
      if (/[\p{L}\p{N}]/u.test(trimmed)) out.push(trimmed);
    }
  }
  return out;
}

export function normalizeSentence(sentence: string): string {
  return sentence.normalize("NFC").toLowerCase().replace(/\s+/gu, " ").trim();
}

export function countWords(sentence: string): number {
  return sentence.split(/\s+/u).filter((token) => /[\p{L}\p{N}]/u.test(token)).length;
}

function sentenceSet(text: string): Set<string> {
  return new Set(splitSentences(text).map(normalizeSentence));
}

function editsSet(edits: readonly AuthorshipEdit[], status: AuthorshipEdit["status"]) {
  const set = new Set<string>();
  for (const edit of edits)
    if (edit.status === status)
      for (const sentence of sentenceSet(edit.inserted_text)) set.add(sentence);
  return set;
}

/**
 * Rounds exact shares to multiples of `step` that add up to 100 (largest
 * remainder). A part with any words reads at least `step`, so a small share
 * of the assistant's text never shows as 0 %.
 */
export function roundShares(
  parts: readonly number[],
  step: number = AUTHORSHIP_ROUND_TO,
): number[] {
  const total = parts.reduce((sum, part) => sum + part, 0);
  if (total <= 0) return parts.map(() => 0);
  const units = 100 / step;
  const exact = parts.map((part) => (part / total) * units);
  const floors = exact.map(Math.floor);
  let left = units - floors.reduce((sum, value) => sum + value, 0);
  const order = exact
    .map((value, index) => ({ index, rest: value - Math.floor(value) }))
    .sort((a, b) => b.rest - a.rest || a.index - b.index);
  for (const { index } of order) {
    if (left <= 0) break;
    floors[index] += 1;
    left -= 1;
  }
  // Something small is still something: never round a part with words to 0 %.
  for (let index = 0; index < parts.length; index += 1) {
    if (parts[index] <= 0 || floors[index] > 0) continue;
    const largest = floors.indexOf(Math.max(...floors));
    floors[index] = 1;
    floors[largest] -= 1;
  }
  return floors.map((value) => value * step);
}

export function estimateAuthorship(input: AuthorshipInput): AuthorshipEstimate {
  const accepted = editsSet(input.edits, "accepted");
  const pending = editsSet(input.edits, "pending");
  const baselineSet =
    input.baseline.kind === "unknown" ? null : sentenceSet(input.baseline.text);
  const baselineKind: DocumentAuthorshipBaseline = input.baseline.kind;

  const words: DocumentAuthorshipWords = { total: 0, person: 0, ai: 0, undetermined: 0 };
  for (const sentence of splitSentences(input.text)) {
    const key = normalizeSentence(sentence);
    const count = countWords(sentence);
    const long = count >= AUTHORSHIP_MIN_WORDS;
    let owner: "person" | "ai" | "undetermined";
    if (accepted.has(key)) owner = long ? "ai" : "undetermined";
    else if (pending.has(key)) owner = "undetermined";
    else if (baselineSet === null) owner = "undetermined";
    else if (baselineSet.has(key))
      owner = baselineKind === "ai" && long ? "ai" : "undetermined";
    else owner = "person";
    words[owner] += count;
    words.total += count;
  }

  const counts = { accepted: 0, rejected: 0, pending: 0 };
  for (const edit of input.edits) counts[edit.status] += 1;

  const [person, ai, undetermined] = roundShares([
    words.person,
    words.ai,
    words.undetermined,
  ]);
  return {
    baseline: baselineKind,
    words,
    shares: words.total > 0 ? { person, ai, undetermined } : null,
    edits: counts,
    textless_pages: input.textlessPages ?? 0,
  };
}
